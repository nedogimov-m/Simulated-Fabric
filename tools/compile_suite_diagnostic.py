#!/usr/bin/env python3
"""Snapshot and type-check all migrating suite/dependency Java sources together.

This diagnostic creates no JAR, runs no tests and bypasses no production build
prerequisite. Incomplete Sable/Veil APIs come from their actual migrating sources.
Legacy optional integration JARs are compile references only; this is not a
claim that those optional integrations run on 26.3. Requires the resolved Sable
classpath plus genuine Create/Companion artifacts. The final Loom build is still
mandatory, with no source filtering.
"""
import collections
import hashlib
import json
import os
from pathlib import Path
import re
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
WORK = ROOT / 'build/porting/suite-diagnostic'
WORK.mkdir(parents=True, exist_ok=True)
JAVA_HOME = Path(os.environ['JAVA_HOME'])
sable_args = ROOT / 'ports/sable/build/diagnostic/server-migration.args'
args = sable_args.read_text().splitlines()
resolved = args[args.index('-classpath') + 1].split(os.pathsep)
cache = Path.home() / '.gradle/caches'
create = ROOT.parent / '26_3_porting/build/libs/create-fabric-6.0.10-port.2+mc26.3.jar'
companion = ROOT / 'ports/companion/build/libs/sable-companion-fabric-26.3-1.6.0-port.1+mc26.3.jar'
# Loom's processed target includes genuine Fabric interface injection/access.
# Raw Mojang bytecode would falsely reject already accepted native renderer/tab APIs.
loom_targets = sorted((ROOT / 'ports/model-tests/.gradle/loom-cache/minecraftMaven/net/minecraft').glob(
    'minecraft-merged-*/26.3/*.jar'))
if len(loom_targets) != 1:
    raise SystemExit('Resolve model-tests compileClasspath once to provide one processed Minecraft26.3 target.')
loom_target = loom_targets[0]
access_target = WORK / 'minecraft-fabric-sable-access.jar'
aw = ROOT / 'ports/sable/common/src/main/resources/sable.accesswidener'
sim_aw = ROOT / 'simulated/fabric/src/main/resources/simulated.native.accesswidener'
veil_aw = ROOT / 'ports/veil/common/src/main/resources/veil.native.accesswidener'
combined_aw = WORK / 'suite.accesswidener'
combined_aw.write_text(aw.read_text().rstrip() + '\n' + '\n'.join(sim_aw.read_text().splitlines()[1:]) + '\n' + '\n'.join(veil_aw.read_text().splitlines()[1:]) + '\n')
access_key = hashlib.sha256(combined_aw.read_bytes() + str(loom_target.stat().st_mtime_ns).encode()).hexdigest()
key_file = WORK / 'minecraft-access.key'
if not access_target.exists() or not key_file.exists() or key_file.read_text() != access_key:
    # Reuse the real ClassTweaker driver generated by the dependency diagnostic.
    driver = ROOT / 'ports/sable/build/diagnostic/ApplySableAccess.java'
    modules = cache / 'modules-2/files-2.1'
    driver_cp = list((modules / 'net.fabricmc/class-tweaker/0.3.0').glob('*/*.jar'))
    driver_cp += list((modules / 'org.ow2.asm').glob('*/9.10.1/*/*.jar'))
    driver_cp = os.pathsep.join(map(str, driver_cp))
    subprocess.run([str(JAVA_HOME / 'bin/javac'), '--release', '25', '-proc:none', '-cp', driver_cp,
                    '-d', str(WORK), str(driver)], check=True)
    subprocess.run([str(JAVA_HOME / 'bin/java'), '-cp', str(WORK) + os.pathsep + driver_cp,
                    'ApplySableAccess', str(loom_target), str(combined_aw), str(access_target)], check=True)
    key_file.write_text(access_key)
classpath = [access_target, create, companion]
# Real native ImGuiMC dependency first: Flashback embeds an older imgui.ImGui
# class and must not silently shadow the actual UI API required by this port.
imgui_binding = ROOT / 'ports/imguimc/libraries/imgui-java-binding-1.92.7.1.jar'
if not imgui_binding.is_file():
    raise SystemExit(f'Missing genuine native ImGui API: {imgui_binding}')
classpath.append(imgui_binding)
iris_api = ROOT / 'ports/veil/libraries/iris-fabric-1.11.7+mc26.3.jar'
if not iris_api.is_file():
    raise SystemExit(f'Missing genuine optional Iris26.3 API: {iris_api}')
classpath.append(iris_api)
sodium_targets = list((cache / 'modules-2/files-2.1/maven.modrinth/sodium/mc26.3-0.9.2-fabric').glob('*/*.jar'))
if len(sodium_targets) != 1:
    raise SystemExit('Resolve the genuine Sodium mc26.3-0.9.2-fabric optional compile target once.')
classpath.append(sodium_targets[0])
jei_version = '31.16.0.87'
for side in ('common', 'fabric'):
    api = ROOT / 'ports/optional-api' / f'jei-26.3-{side}-api-{jei_version}.jar'
    if not api.is_file():
        raise SystemExit(f'Missing genuine JEI26.3 optional compile API: {api}')
    classpath.append(api)
for filename in ('NaturesCompass-26.3-2.5.1-fabric.jar', 'ExplorersCompass-26.3-2.5.2-fabric.jar'):
    api = ROOT / 'ports/optional-api' / filename
    if not api.is_file():
        raise SystemExit(f'Missing genuine26.3 optional compass compile target: {api}')
    classpath.append(api)
# Keep Create/Ponder/Flywheel/Registrate and all Minecraft/Fabric versions other
# than the genuine target out of fallback resolution. Source migrations must
# expose removed classes, rather than silently finding old implementations.
for raw in resolved:
    path = Path(raw)
    if not path.exists() or path in classpath:
        continue
    if 'sodium' in path.name.lower():
        continue  # The single genuine26.3 optional target is already first.
    if any(token in raw for token in (
            'minecraft-26.3-sable-access.jar', '/net/minecraft/', '/net.minecraft/',
            '/com.simibubi.create/', '/net.createmod.ponder/', '/com.tterrag.',
            '/dev.engine-room.', '/dev.engine_room.', '/flywheel-', '/registrate/',
            '/mezz.jei/',
            '/foundry/imguimc/', '/target-api/iris.jar', '/maven.modrinth/iris/',
            '/maven.modrinth/sodium/', '/net.caffeinemc.mods/sodium', '/sodium-fabric/', '/sodium-neoforge/',
            '/naturescompass/', '/explorerscompass/',
            'veil-4.3.2-upstream-diagnostic-only.jar')):
        continue
    if '/net.fabricmc.fabric-api/' in raw and '/fabric-api-26.3/' not in raw:
        continue
    # Exact current Fabric module JARs and Minecraft libraries are already first
    # in Sable's resolved diagnostic list. Actual source classes take precedence
    # over any same-named bytecode from its narrowly compiled API directories.
    if path not in classpath:
        classpath.append(path)
energy = cache / 'modules-2/files-2.1/teamreborn/energy/5.0.0'
classpath += [p for p in energy.rglob('*.jar') if not p.name.endswith(('-sources.jar', '-javadoc.jar'))]
for needed in classpath[:3]:
    if not needed.is_file():
        raise SystemExit(f'Missing genuine target prerequisite: {needed}')

source_roots = [ROOT / module / side / 'src/main/java'
                for module in ('simulated', 'aeronautics', 'offroad') for side in ('common', 'fabric')]
source_roots += [ROOT / 'ports/sable' / side / 'src/main/java' for side in ('common', 'fabric', 'sable_rapier')]
source_roots += [ROOT / 'ports/veil' / side / 'src/main/java' for side in ('common', 'fabric')]
source_roots += [ROOT / 'ports/imguimc' / side / 'src/main/java' for side in ('common', 'fabric')]
snapshot = WORK / 'sources'
files = {}
sources = []
for directory in source_roots:
    for path in sorted(directory.rglob('*.java')):
        relative = path.relative_to(ROOT)
        content = path.read_bytes()
        destination = snapshot / relative
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_bytes(content)
        files[str(relative)] = hashlib.sha256(content).hexdigest()
        sources.append(destination)
manifest = {'minecraft': '26.3', 'java': 25, 'source_count': len(sources),
            'sources': files, 'classpath': list(map(str, classpath)),
            'minecraft_fabric_target': str(loom_target), 'sable_accesswidener_sha256': hashlib.sha256(aw.read_bytes()).hexdigest(),
            'simulated_accesswidener_sha256': hashlib.sha256(sim_aw.read_bytes()).hexdigest(),
            'veil_native_accesswidener_sha256': hashlib.sha256(veil_aw.read_bytes()).hexdigest(),
            'limitations': __doc__.strip()}
(WORK / 'inputs.json').write_text(json.dumps(manifest, indent=2) + '\n')
classes = WORK / 'classes'
classes.mkdir(exist_ok=True)
javac_args = ['--release', '25', '-proc:none', '-sourcepath', '""', '-Xmaxerrs', '10000',
              '-d', str(classes), '-classpath', os.pathsep.join(map(str, classpath))] + list(map(str, sources))
argfile = WORK / 'javac.args'
argfile.write_text('\n'.join(javac_args) + '\n')
log = WORK / 'javac.log'
with log.open('w') as output:
    result = subprocess.run([str(JAVA_HOME / 'bin/javac'), '@' + str(argfile)], stdout=output, stderr=subprocess.STDOUT)
issues = []
for match in re.finditer(r'^(.+\.java):(\d+): error: (.+)$', log.read_text(), re.M):
    relative = str(Path(match[1]).relative_to(snapshot))
    issues.append({'file': relative, 'line': int(match[2]), 'message': match[3]})
groups = collections.Counter()
for issue in issues:
    parts = issue['file'].split('/')
    groups['/'.join(parts[:2]) if parts[0] == 'ports' else parts[0]] += 1
report = {'exit_code': result.returncode, 'sources': len(sources), 'errors': len(issues),
          'by_component': dict(groups), 'issues': issues,
          'limitations': 'Diagnostic snapshot only; no distribution or full Loom/Mixin/runtime success.'}
(WORK / 'report.json').write_text(json.dumps(report, indent=2) + '\n')
print(f'Complete-source snapshot: {len(sources)} sources; javac exit {result.returncode}; {len(issues)} errors')
for component, count in groups.most_common():
    print(f'  {component}: {count}')
print(f'Report: {WORK / "report.json"}')
raise SystemExit(result.returncode)
